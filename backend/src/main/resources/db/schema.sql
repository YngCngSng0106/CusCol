CREATE TABLE IF NOT EXISTS `sys_user` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `username` VARCHAR(50) NOT NULL COMMENT '用户名',
  `password` VARCHAR(100) NOT NULL COMMENT '密码（BCrypt密文）',
  `phone` VARCHAR(20) NOT NULL COMMENT '手机号',
  `email` VARCHAR(100) NOT NULL COMMENT '邮箱',
  `city` VARCHAR(50) NULL COMMENT '所在城市',
  `status` TINYINT NOT NULL DEFAULT 1 COMMENT '状态：1正常 0停用',
  `last_login_time` DATETIME NULL COMMENT '最后登录时间',
  `iz_deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '是否删除：1是 0否',
  `create_by` BIGINT UNSIGNED NULL COMMENT '创建人',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_by` BIGINT UNSIGNED NULL COMMENT '更新人',
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_username` (`username`),
  UNIQUE KEY `uk_phone` (`phone`),
  UNIQUE KEY `uk_email` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户表';

CREATE TABLE IF NOT EXISTS `sys_verification_code` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `target` VARCHAR(100) NOT NULL COMMENT '接收方（手机号或邮箱）',
  `target_type` TINYINT NOT NULL COMMENT '接收类型：1手机 2邮箱',
  `scene` TINYINT NOT NULL COMMENT '场景：1注册 2找回密码 3登录',
  `code` VARCHAR(10) NOT NULL COMMENT '验证码',
  `expire_time` DATETIME NOT NULL COMMENT '过期时间',
  `iz_used` TINYINT NOT NULL DEFAULT 0 COMMENT '是否已使用：1是 0否',
  `send_ip` VARCHAR(50) NULL COMMENT '请求IP',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_target_scene` (`target`, `scene`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='验证码表';

