CREATE TABLE IF NOT EXISTS `attachment` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `biz_type` TINYINT NOT NULL COMMENT '业务类型：1客户 2客户项目 3拜访记录 4合同 5用户头像',
  `biz_id` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '业务ID，0表示临时未绑定',
  `attach_kind` TINYINT NOT NULL COMMENT '附件类别：1图片 2合同正本 3补充协议 4发票 5拜访现场资料 6其他',
  `file_name` VARCHAR(255) NOT NULL COMMENT '原始文件名',
  `file_key` VARCHAR(500) NOT NULL COMMENT '存储相对路径',
  `file_url` VARCHAR(1000) NULL COMMENT '公开访问地址，鉴权文件为空',
  `thumb_key` VARCHAR(500) NULL COMMENT '缩略图相对路径',
  `thumb_url` VARCHAR(1000) NULL COMMENT '缩略图访问地址',
  `file_ext` VARCHAR(20) NOT NULL COMMENT '扩展名',
  `mime_type` VARCHAR(100) NOT NULL COMMENT 'MIME类型',
  `file_size` BIGINT UNSIGNED NOT NULL COMMENT '文件大小（字节）',
  `file_md5` CHAR(32) NULL COMMENT '文件MD5',
  `storage_type` TINYINT NOT NULL DEFAULT 1 COMMENT '存储类型：1本地 2MinIO 3OSS',
  `access_type` TINYINT NOT NULL DEFAULT 1 COMMENT '访问方式：1公开直链 2鉴权下载',
  `sort_no` INT NOT NULL DEFAULT 0 COMMENT '排序号',
  `iz_deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '是否删除：1是 0否',
  `create_by` BIGINT UNSIGNED NULL COMMENT '上传人',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '上传时间',
  `update_by` BIGINT UNSIGNED NULL COMMENT '更新人',
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_file_key` (`file_key`),
  KEY `idx_biz` (`biz_type`, `biz_id`, `iz_deleted`, `sort_no`),
  KEY `idx_md5` (`file_md5`),
  KEY `idx_temp` (`biz_id`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='统一附件表';
